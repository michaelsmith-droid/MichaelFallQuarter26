def Add(num1, num2):
    return num1 + num2

sum = Add(7, 18)
print(sum)


def Subtract(num1, num2):
    return num1 - num2
difference = Subtract(5, 10)
print(difference)


def Multiply(num1, num2):
    return num1 * num2
produce = Multiply(2, 9)
print(produce)


def Divide(num1, num2):
    return num1 / num2
quotient = Divide(11, 8)
print(quotient)