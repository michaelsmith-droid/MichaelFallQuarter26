numberGrade = int(input("Enter Your Grade: "))
if(numberGrade >= 90):
    print("You Got an A, Excellent Work!")
elif(numberGrade >= 80 and numberGrade < 90):
    print("You Got a B, Pretty Good!")
elif(numberGrade >= 70 and numberGrade < 80):
    print("You Got a C, Solid Effort!")
elif(numberGrade >= 60 and numberGrade < 70):
    print("You Got a D, kinda wack ngl!")
elif(numberGrade <= 60):
    print("You Got an F, It's Official, You Suck!")    